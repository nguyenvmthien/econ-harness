run <- function(script, args = character()) {
  output <- system2(Sys.which("Rscript"), c(shQuote(script), args), stdout = TRUE, stderr = TRUE)
  status <- attr(output, "status")
  if (is.null(status)) status <- 0L
  list(status = status, output = output)
}
